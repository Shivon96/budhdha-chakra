import { ChakraTopology, HardwareExportConfig } from '../types/chakra';

/**
 * Generates ready-to-flash FastLED C++ Arduino/ESP-01/ESP8266/ESP32 code (.ino)
 * tailored to the exact user topology, spoke/segment count, LEDs per strip, and wiring layout.
 */
export function generateFastLedCode(
  topology: ChakraTopology,
  totalLeds: number,
  config: HardwareExportConfig
): string {
  const { chipType, dataPin, ledType, colorOrder, maxMilliamps, hasButtonControl, buttonPin, hasBrightnessPot, potPin } = config;

  let topologyDef = '';
  let mappingFunction = '';
  const isEsp01 = chipType === 'esp01';
  const isEsp = chipType === 'esp01' || chipType === 'esp8266' || chipType === 'esp32';

  if (topology.type === 'spokes') {
    const { spokeCount, ledsPerSpoke, bottomGapDeg, wiring } = topology.spokes;
    topologyDef = `
// ================= TOPOLOGY SPECIFICATION =================
#define TOPOLOGY_SPOKES
#define NUM_SPOKES      ${spokeCount}   // Number of radial segments / strips
#define LEDS_PER_SPOKE  ${ledsPerSpoke}    // Number of LEDs per segment
#define BOTTOM_GAP_DEG  ${bottomGapDeg || 0}    // Bottom cutout angle for statue
#define NUM_LEDS        (${spokeCount} * ${ledsPerSpoke}) // Total LEDs: ${totalLeds}
`;

    if (wiring === 'zigzag') {
      mappingFunction = `
// 2D Matrix coordinate mapping: Segment & LED-in-strip to linear index
// Zigzag wiring: Spoke 0 inward->outward, Spoke 1 outward->inward (links adjacent tips)
uint16_t XY(uint8_t spoke, uint8_t pos) {
  if (spoke >= NUM_SPOKES || pos >= LEDS_PER_SPOKE) return NUM_LEDS;
  if (spoke % 2 == 1) {
    // Odd spoke wired in reverse (tip to center)
    return (spoke * LEDS_PER_SPOKE) + (LEDS_PER_SPOKE - 1 - pos);
  } else {
    // Even spoke wired center to tip
    return (spoke * LEDS_PER_SPOKE) + pos;
  }
}
`;
    } else if (wiring === 'inward') {
      mappingFunction = `
// Inward wiring: All strips wired from outer rim to center
uint16_t XY(uint8_t spoke, uint8_t pos) {
  if (spoke >= NUM_SPOKES || pos >= LEDS_PER_SPOKE) return NUM_LEDS;
  return (spoke * LEDS_PER_SPOKE) + (LEDS_PER_SPOKE - 1 - pos);
}
`;
    } else {
      mappingFunction = `
// Outward wiring: All strips wired from center out to the tip
uint16_t XY(uint8_t spoke, uint8_t pos) {
  if (spoke >= NUM_SPOKES || pos >= LEDS_PER_SPOKE) return NUM_LEDS;
  return (spoke * LEDS_PER_SPOKE) + pos;
}
`;
    }
  } else if (topology.type === 'concentric') {
    const rings = topology.concentric.rings;
    topologyDef = `
// ================= CONCENTRIC RINGS TOPOLOGY =================
#define TOPOLOGY_CONCENTRIC
#define NUM_RINGS       ${rings.length}
#define NUM_LEDS        ${totalLeds}

const uint16_t RING_SIZES[NUM_RINGS] = { ${rings.map(r => r.ledCount).join(', ')} };
`;
    mappingFunction = `
uint16_t getRingStartIndex(uint8_t ring) {
  uint16_t idx = 0;
  for (uint8_t i = 0; i < ring && i < NUM_RINGS; i++) {
    idx += RING_SIZES[i];
  }
  return idx;
}
`;
  } else {
    const h = topology.hybrid;
    topologyDef = `
// ================= HYBRID CHAKRA TOPOLOGY =================
#define TOPOLOGY_HYBRID
#define CENTER_LEDS     ${h.centerLedCount}
#define NUM_SPOKES      ${h.spokeCount}
#define LEDS_PER_SPOKE  ${h.ledsPerSpoke}
#define OUTER_RING_LEDS ${h.outerRingLedCount}
#define NUM_LEDS        ${totalLeds}
`;
    mappingFunction = `
uint16_t getCenterLed(uint8_t i) { return (i % CENTER_LEDS); }
uint16_t getSpokeLed(uint8_t spoke, uint8_t pos) {
  return CENTER_LEDS + (spoke * LEDS_PER_SPOKE) + pos;
}
uint16_t getOuterRingLed(uint8_t i) {
  return CENTER_LEDS + (NUM_SPOKES * LEDS_PER_SPOKE) + (i % OUTER_RING_LEDS);
}
`;
  }

  const esp01Notes = isEsp01
    ? ` *  [ESP-01 / ESP-01S Hardware Pinout Notes]
 *  - VCC: Must be regulated 3.3V (Do NOT feed 5V directly to ESP-01!)
 *  - GND: Common ground with 5V Power Supply & WS2812 strip
 *  - CH_PD (EN): Pull HIGH to 3.3V (10k resistor or direct 3.3V)
 *  - GPIO 2: Data Output (DIN) to WS2812 strip (Pin ${dataPin})
 *  - GPIO 0: Connect to GND ONLY while flashing in Arduino IDE; leave floating/HIGH to run!
 *  - Baud rate for flashing: 115200 Baud (Generic ESP8266 Module in Arduino IDE)
`
    : '';

  return `/**
 * =========================================================================
 * BUDDHA CHAKRA WS2812 CONTROLLER
 * Target Hardware: ${isEsp01 ? 'ESP-01 / ESP-01S (ESP8266)' : chipType.toUpperCase()}
 * Compiled for: ${totalLeds} Pixel LEDs
 * Generated by: Buddha Chakra WS2812 Studio
 * =========================================================================
 * 
 * Hardware Connections:
 *  - 5V Power Supply (+) ---> WS2812 5V rail (Inject every ~60 LEDs)
 *  - GND Power Supply (-) ---> WS2812 GND and Microcontroller GND
 *  - Data Line (DIN)     ---> GPIO Pin ${dataPin} (via 330 ohm resistor)
${esp01Notes}${hasButtonControl && !isEsp01 ? ` *  - Push Button         ---> Pin ${buttonPin} (Internal Pullup, to GND)\n` : ''}${hasBrightnessPot && !isEsp01 ? ` *  - Potentiometer       ---> Analog Pin A${potPin}\n` : ''} */

#include <FastLED.h>

#define DATA_PIN        ${dataPin}
#define LED_TYPE        ${ledType}
#define COLOR_ORDER     ${colorOrder}
#define MAX_POWER_MA    ${maxMilliamps} // Hardware current limit in mA

${topologyDef}
${hasButtonControl && !isEsp01 ? `#define BUTTON_PIN      ${buttonPin}\n` : ''}${hasBrightnessPot && !isEsp01 ? `#define POT_PIN         ${potPin}\n` : ''}
CRGB leds[NUM_LEDS];

// ---------------- SACRED BUDDHIST FLAG COLORS (SHADVARNA) ----------------
// 1. Blue (Neela), 2. Yellow (Peetha), 3. Red (Lohitha), 4. White (Odata), 5. Orange (Manjesta)
const CRGB SHADVARNA_COLORS[5] = {
  CRGB(0, 56, 168),    // Sapphire Blue
  CRGB(255, 215, 0),   // Golden Yellow
  CRGB(209, 18, 18),   // Ruby Red
  CRGB(255, 255, 255), // Pure White
  CRGB(255, 106, 0)    // Saffron Orange
};

uint8_t currentPattern = 0;
uint8_t globalBrightness = 200;
unsigned long lastPatternChange = 0;
const uint16_t AUTO_CYCLE_SECONDS = 15; // Cycle pattern every 15 seconds

${mappingFunction}

// ---------------- ANIMATION PATTERN FUNCTIONS ----------------

// 1. Radiant Ray Burst: Pulses outward from center along segments
void pattern_vihidena_ras(uint32_t step) {
  fadeToBlackBy(leds, NUM_LEDS, 45);
#if defined(TOPOLOGY_SPOKES)
  uint8_t wavePos = (step / 2) % LEDS_PER_SPOKE;
  CRGB waveColor = SHADVARNA_COLORS[(step / 30) % 5];
  for (uint8_t s = 0; s < NUM_SPOKES; s++) {
    uint16_t idx = XY(s, wavePos);
    if (idx < NUM_LEDS) leds[idx] = waveColor;
  }
#else
  uint16_t pulseIndex = (step * 3) % NUM_LEDS;
  leds[pulseIndex] = SHADVARNA_COLORS[(step / 20) % 5];
#endif
}

// 2. Spinning Wheel of Dharma: Circular rotation with trailing fade
void pattern_karakenna_chakra(uint32_t step) {
  fadeToBlackBy(leds, NUM_LEDS, 60);
#if defined(TOPOLOGY_SPOKES)
  uint8_t activeSpoke = (step / 3) % NUM_SPOKES;
  CRGB spokeColor = ColorFromPalette(RainbowColors_p, step * 2, 255, LINEARBLEND);
  for (uint8_t p = 0; p < LEDS_PER_SPOKE; p++) {
    uint16_t idx = XY(activeSpoke, p);
    if (idx < NUM_LEDS) leds[idx] = spokeColor;
  }
#else
  for (uint16_t i = 0; i < NUM_LEDS; i++) {
    leds[i] = ColorFromPalette(RainbowColors_p, i * 4 + step, 255, LINEARBLEND);
  }
#endif
}

// 3. Six-Color Flag Revolver: Revolving sacred color sectors
void pattern_shadvarna_bhranama(uint32_t step) {
#if defined(TOPOLOGY_SPOKES)
  for (uint8_t s = 0; s < NUM_SPOKES; s++) {
    uint8_t sector = (s + (step / 6)) % 5;
    CRGB col = SHADVARNA_COLORS[sector];
    for (uint8_t p = 0; p < LEDS_PER_SPOKE; p++) {
      uint16_t idx = XY(s, p);
      if (idx < NUM_LEDS) leds[idx] = col;
    }
  }
#else
  for (uint16_t i = 0; i < NUM_LEDS; i++) {
    uint8_t colIdx = ((i * 5 / NUM_LEDS) + (step / 10)) % 5;
    leds[i] = SHADVARNA_COLORS[colIdx];
  }
#endif
}

// 4. Spiral Galaxy Vortex: Smooth spiral pinwheel waves
void pattern_kundalani_spiral(uint32_t step) {
#if defined(TOPOLOGY_SPOKES)
  for (uint8_t s = 0; s < NUM_SPOKES; s++) {
    for (uint8_t p = 0; p < LEDS_PER_SPOKE; p++) {
      uint8_t wave = sin8((s * 256 / NUM_SPOKES) + (p * 28) - (step * 4));
      uint16_t idx = XY(s, p);
      if (idx < NUM_LEDS) {
        leds[idx] = ColorFromPalette(PartyColors_p, wave + step, wave, LINEARBLEND);
      }
    }
  }
#else
  for (uint16_t i = 0; i < NUM_LEDS; i++) {
    leds[i] = ColorFromPalette(PartyColors_p, i * 8 - step * 4, 255, LINEARBLEND);
  }
#endif
}

// 5. Shooting Meteors: Luminous comets racing along rays
void pattern_ulkapaatha_meteor(uint32_t step) {
  fadeToBlackBy(leds, NUM_LEDS, 50);
#if defined(TOPOLOGY_SPOKES)
  uint8_t spoke = (step / 16) % NUM_SPOKES;
  uint8_t pos = (step % 16);
  if (pos < LEDS_PER_SPOKE) {
    uint16_t idx = XY(spoke, pos);
    if (idx < NUM_LEDS) leds[idx] = CRGB::White;
  }
#else
  uint16_t pos = step % NUM_LEDS;
  leds[pos] = CRGB::White;
#endif
}

// 6. Sacred Twinkling Starlight: Peaceful starlight shimmer
void pattern_tharu_eli_sparkle(uint32_t step) {
  fadeToBlackBy(leds, NUM_LEDS, 30);
  if (random8() < 90) {
    uint16_t idx = random16(NUM_LEDS);
    leds[idx] = (random8() < 128) ? CRGB::White : SHADVARNA_COLORS[random8(5)];
  }
}

// 7. Meditative Aura Breath: Soft harmonic breathing cycle
void pattern_prana_spandana(uint32_t step) {
  uint8_t breath = beatsin8(14, 40, 255);
  CRGB col = SHADVARNA_COLORS[(step / 120) % 5];
  col.nscale8(breath);
  fill_solid(leds, NUM_LEDS, col);
}

// ---------------- SETUP & LOOP ----------------
void setup() {
  Serial.begin(115200);
  delay(1000); // Startup safety delay

  FastLED.addLeds<LED_TYPE, DATA_PIN, COLOR_ORDER>(leds, NUM_LEDS).setCorrection(TypicalLEDStrip);
  FastLED.setMaxPowerInVoltsAndMilliamps(5, MAX_POWER_MA);
  FastLED.setBrightness(globalBrightness);

${hasButtonControl && !isEsp01 ? `  pinMode(BUTTON_PIN, INPUT_PULLUP);\n` : ''}  Serial.println(F("Buddha Chakra Controller Initialized!"));
}

uint32_t stepCounter = 0;

void loop() {
${hasButtonControl && !isEsp01 ? `  // Cycle pattern via push button with debounce
  static bool lastBtnState = HIGH;
  bool btnState = digitalRead(BUTTON_PIN);
  if (btnState == LOW && lastBtnState == HIGH) {
    currentPattern = (currentPattern + 1) % 7;
    fill_solid(leds, NUM_LEDS, CRGB::Black);
    delay(200);
  }
  lastBtnState = btnState;\n\n` : ''}${hasBrightnessPot && !isEsp01 ? `  // Read brightness potentiometer
  int potVal = analogRead(POT_PIN);
  globalBrightness = map(potVal, 0, 1023, 15, 255);
  FastLED.setBrightness(globalBrightness);\n\n` : ''}  // Auto advance pattern every ${15} seconds
  if (millis() - lastPatternChange > (AUTO_CYCLE_SECONDS * 1000UL)) {
    currentPattern = (currentPattern + 1) % 7;
    lastPatternChange = millis();
    fill_solid(leds, NUM_LEDS, CRGB::Black);
  }

  // Execute active pattern
  switch (currentPattern) {
    case 0: pattern_vihidena_ras(stepCounter); break;
    case 1: pattern_karakenna_chakra(stepCounter); break;
    case 2: pattern_shadvarna_bhranama(stepCounter); break;
    case 3: pattern_kundalani_spiral(stepCounter); break;
    case 4: pattern_ulkapaatha_meteor(stepCounter); break;
    case 5: pattern_tharu_eli_sparkle(stepCounter); break;
    case 6: pattern_prana_spandana(stepCounter); break;
  }

  FastLED.show();
  stepCounter++;
  delay(20);
}
`;
}

export function generateWledLedMap(totalLeds: number): string {
  const mapArray = Array.from({ length: totalLeds }, (_, i) => i);
  const ledmapObj = {
    n: "Buddha Chakra Halo",
    width: totalLeds,
    height: 1,
    map: mapArray,
  };
  return JSON.stringify(ledmapObj, null, 2);
}
